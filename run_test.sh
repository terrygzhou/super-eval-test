#!/usr/bin/env bash
# ─────────────────────────────────────────────────────────────
# SuperApp Test — Automated Setup & Run Script
# ─────────────────────────────────────────────────────────────
set -euo pipefail

# ── Defaults (override via env vars) ──────────────────────────
: "${SUPERAPP_TARGET_URL:=http://localhost:8081}"
: "${SUPERAPP_SOURCE_ROOT:=~/workspace/projects/loop_factory}"
: "${SUPERAPP_OUTPUT_DIR:=~/workspace/projects/loop_factory/superApp_output}"
: "${SUPERAPP_MODE:=agent}"           # scripted | agent
: "${SUPERAPP_LLM_URL:=http://pop-os:8080}"
: "${SUPERAPP_LLM_MODEL:=Qwen3.6-27B}"
: "${SUPERAPP_LLM_API_KEY:=not-needed}"
: "${SUPERAPP_VARIATIONS:=3}"
: "${SUPERAPP_DRY_RUN:=false}"
: "${SUPERAPP_HEADLESS:=true}"
: "${SUPERAPP_TIMEOUT_MS:=30000}"
: "${SUPERAPP_LOG_TYPE:=docker}"
: "${SUPERAPP_LOG_CONTAINER:=loop_factory_web}"
: "${SUPERAPP_OPENHANDS_TIMEOUT:=2400}"   # agent mode only
: "${SUPERAPP_OPENHANDS_START:=true}"   # auto-start OH container in agent mode

: "${SUPERAPP_GATE:=false}"          # run evaluation gate
: "${SUPERAPP_GATE_N:=7}"            # trials per task (5-10)
: "${SUPERAPP_GATE_SUITE:=tasks}"    # task suite directory
: "${SUPERAPP_GATE_BASELINE:=}"      # optional prior baseline path

# ── Colours ───────────────────────────────────────────────────
R='\033[0;31m'; G='\033[0;32m'; Y='\033[0;33m'; B='\033[0;34m'; NC='\033[0m'

info()  { echo -e "${B}[INFO]${NC}  $*"; }
warn()  { echo -e "${Y}[WARN]${NC}  $*"; }
ok()    { echo -e "${G}[OK]${NC}    $*"; }
fail()  { echo -e "${R}[FAIL]${NC}  $*"; exit 1; }

# ── Resolve script directory (portable) ──────────────────────
SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
cd "$SCRIPT_DIR"

info "SuperApp Test Pipeline"
info "Script dir: $SCRIPT_DIR"
info ""
info "Configuration:"
info "  Target URL       : $SUPERAPP_TARGET_URL"
info "  Source root      : $SUPERAPP_SOURCE_ROOT"
info "  Output dir       : $SUPERAPP_OUTPUT_DIR"
info "  Mode             : $SUPERAPP_MODE"
info "  LLM URL          : $SUPERAPP_LLM_URL"
info "  LLM Model        : $SUPERAPP_LLM_MODEL"
info "  Variations       : $SUPERAPP_VARIATIONS"
info "  Dry run          : $SUPERAPP_DRY_RUN"
info "  Browser headless : $SUPERAPP_HEADLESS"
info "  Log container    : $SUPERAPP_LOG_CONTAINER"
info ""

# ── Step 1: Check prerequisites ──────────────────────────────
info "Checking prerequisites..."

command -v python3 >/dev/null 2>&1 || fail "python3 not found"
command -v uv     >/dev/null 2>&1 || fail "uv not found — install from https://github.com/astral-sh/uv"

if [[ "$SUPERAPP_MODE" == "agent" ]]; then
    command -v docker >/dev/null 2>&1 || fail "docker required for agent mode"
    docker compose version >/dev/null 2>&1 || fail "docker compose v2 required"
fi

# ── Step 2: Install dependencies ──────────────────────────────
if [[ ! -d ".venv" ]]; then
    info "Creating virtual environment..."
    uv venv
fi

source .venv/bin/activate
info "Syncing dependencies..."
uv sync --quiet

# ── Step 3: Install Playwright browsers (scripted mode) ───────
if [[ "$SUPERAPP_MODE" == "scripted" ]]; then
    info "Checking Playwright browsers..."
    python -m playwright install chromium 2>/dev/null || warn "Playwright install failed (may already be installed)"
fi

# ── Step 4: Write config.yaml ──────────────────────────────────
if [[ -f "config.yaml" && "${SUPERAPP_FORCE_CONFIG:-false}" != "true" ]]; then
    ok "Using existing config.yaml (set SUPERAPP_FORCE_CONFIG=true to regenerate)"
else
    info "Generating config.yaml..."
    cat > config.yaml <<EOF
    # Auto-generated by run_test.sh

    llm:
      base_url: "$SUPERAPP_LLM_URL"
      model: "$SUPERAPP_LLM_MODEL"
      api_key: "$SUPERAPP_LLM_API_KEY"

    target:
      url: "$SUPERAPP_TARGET_URL"
      scan_paths:
        - "/"
        - "/login"
        - "/register"

    source:
      root: "$SUPERAPP_SOURCE_ROOT"
      form_patterns:
        - "**/forms.py"
        - "**/schemas.py"
        - "**/models.py"
        - "**/validators.py"
        - "**/*_form.py"
        - "**/schema*.py"
      route_patterns:
        - "**/routes.py"
        - "**/api.py"
        - "**/endpoints.py"

    logs:
      type: "$SUPERAPP_LOG_TYPE"
      docker_container: "$SUPERAPP_LOG_CONTAINER"
      error_patterns:
        - "ERROR"
        - "Exception"
        - "Traceback"
        - "500"
        - "Connection refused"

    browser:
      headless: $SUPERAPP_HEADLESS
      timeout_ms: $SUPERAPP_TIMEOUT_MS
      viewport:
        width: 1280
        height: 720

    pipeline:
      data_variations: $SUPERAPP_VARIATIONS
EOF
    ok "config.yaml written"
fi

# ── Step 5: Manage OpenHands container (agent mode) ──────────
if [[ "$SUPERAPP_MODE" == "agent" && "$SUPERAPP_OPENHANDS_START" == "true" ]]; then
    info "Starting OpenHands Agent Server..."
    LLM_BASE_URL="$SUPERAPP_LLM_URL" \
    LLM_MODEL="$SUPERAPP_LLM_MODEL" \
    docker compose -f compose.yaml up -d 2>&1 | grep -v "WARN\|deprecated" || true

    info "Waiting for health check..."
    for i in $(seq 1 30); do
        if curl -sf "http://localhost:3005/health" >/dev/null 2>&1; then
            ok "OpenHands is healthy"
            break
        fi
        sleep 2
    done

    if ! curl -sf "http://localhost:3005/health" >/dev/null 2>&1; then
        warn "OpenHands health check timed out — proceeding anyway"
    fi
fi


# ── Step 6: Build CLI arguments ──────────────────────────────────────

if [[ "$SUPERAPP_GATE" == "true" ]]; then
    CLI_ARGS=(
        gate
        --target "$SUPERAPP_TARGET_URL"
        --suite "$SUPERAPP_GATE_SUITE"
        --n "$SUPERAPP_GATE_N"
        --output "$SUPERAPP_OUTPUT_DIR"
        --llm-url "$SUPERAPP_LLM_URL"
        --llm-model "$SUPERAPP_LLM_MODEL"
    )
    if [[ -n "$SUPERAPP_GATE_BASELINE" ]]; then
        CLI_ARGS+=(--baseline "$SUPERAPP_GATE_BASELINE")
    fi
else

CLI_ARGS=(
    run
    --target "$SUPERAPP_TARGET_URL"
    --source "$SUPERAPP_SOURCE_ROOT"
    --output "$SUPERAPP_OUTPUT_DIR"
    --llm-url "$SUPERAPP_LLM_URL"
    --llm-model "$SUPERAPP_LLM_MODEL"
    --variations "$SUPERAPP_VARIATIONS"
    --mode "$SUPERAPP_MODE"
    --agent-timeout "$SUPERAPP_OPENHANDS_TIMEOUT"
)

if [[ "$SUPERAPP_DRY_RUN" == "true" ]]; then
    CLI_ARGS+=(--dry-run)
fi
fi

# ── Step 7: Run the pipeline ──────────────────────────────────
info ""
info "Running pipeline: ${CLI_ARGS[*]}"
echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"

if python -m src "${CLI_ARGS[@]}"; then
    ok ""
    ok "Pipeline complete."
    ok "Reports:"
    ok "  JSON: $SUPERAPP_OUTPUT_DIR/logs/correlation_report.json"
    echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
else
    fail "Pipeline exited with error"
fi

# ── Step 8: Cleanup OpenHands (optional) ──────────────────────
if [[ "$SUPERAPP_MODE" == "agent" && "${SUPERAPP_OPENHANDS_STOP:-false}" == "true" ]]; then
    info "Stopping OpenHands container..."
    docker compose -f compose.yaml down
    ok "OpenHands stopped"
fi