#!/usr/bin/env bash
# ─────────────────────────────────────────────────────────────
# SuperEval Test — Automated Setup & Run Script
# ─────────────────────────────────────────────────────────────
set -euo pipefail

# ── Defaults (override via env vars) ──────────────────────────
: "${SUET_TARGET_URL:=http://localhost:8081}"
: "${SUET_SOURCE_ROOT:=~/workspace/projects/loop_factory}"
: "${SUET_OUTPUT_DIR:=~/workspace/projects/loop_factory/suet_output}"
: "${SUET_MODE:=agent}"           # scripted | agent
: "${SUET_LLM_URL:=http://pop-os:8080}"
: "${SUET_LLM_MODEL:=Qwen3.6-27B}"
: "${SUET_LLM_API_KEY:=not-needed}"
: "${SUET_VARIATIONS:=3}"
: "${SUET_DRY_RUN:=false}"
: "${SUET_HEADLESS:=true}"
: "${SUET_TIMEOUT_MS:=30000}"
: "${SUET_MAX_PAGES:=3}"
: "${SUET_LOG_TYPE:=docker}"
: "${SUET_LOG_CONTAINER:=loop_factory_web}"
: "${SUET_OPENHANDS_TIMEOUT:=2400}"   # agent mode only
: "${SUET_OPENHANDS_START:=true}"   # auto-start OH container in agent mode

# ── Colours ───────────────────────────────────────────────────
R='\033[0;31m'; G='\033[0;32m'; Y='\033[0;33m'; B='\033[0;34m'; NC='\033[0m'

info()  { echo -e "${B}[INFO]${NC}  $*"; }
warn()  { echo -e "${Y}[WARN]${NC}  $*"; }
ok()    { echo -e "${G}[OK]${NC}    $*"; }
fail()  { echo -e "${R}[FAIL]${NC}  $*"; exit 1; }

# ── Resolve script directory (portable) ──────────────────────
SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
cd "$SCRIPT_DIR"

info "SuperEval Test Pipeline"
info "Script dir: $SCRIPT_DIR"
info ""
info "Configuration:"
info "  Target URL       : $SUET_TARGET_URL"
info "  Source root      : $SUET_SOURCE_ROOT"
info "  Output dir       : $SUET_OUTPUT_DIR"
info "  Mode             : $SUET_MODE"
info "  LLM URL          : $SUET_LLM_URL"
info "  LLM Model        : $SUET_LLM_MODEL"
info "  Variations       : $SUET_VARIATIONS"
info "  Dry run          : $SUET_DRY_RUN"
info "  Browser headless : $SUET_HEADLESS"
info "  Log container    : $SUET_LOG_CONTAINER"
info ""

# ── Step 1: Check prerequisites ──────────────────────────────
info "Checking prerequisites..."

command -v python3 >/dev/null 2>&1 || fail "python3 not found"
command -v uv     >/dev/null 2>&1 || fail "uv not found — install from https://github.com/astral-sh/uv"

if [[ "$SUET_MODE" == "agent" ]]; then
    command -v docker >/dev/null 2>&1 || fail "docker required for agent mode"
    docker compose version >/dev/null 2>&1 || fail "docker compose v2 required"
fi

# ── Step 2: Install dependencies ──────────────────────────────
if [[ ! -d ".venv" ]]; then
    info "Creating virtual environment..."
    uv venv
fi

source .venv/bin/activate
info "Syncing dependencies..."
uv sync --quiet

# ── Step 3: Install Playwright browsers (scripted mode) ───────
if [[ "$SUET_MODE" == "scripted" ]]; then
    info "Checking Playwright browsers..."
    python -m playwright install chromium 2>/dev/null || warn "Playwright install failed (may already be installed)"
fi

# ── Step 4: Write config.yaml ──────────────────────────────────
info "Generating config.yaml..."
cat > config.yaml <<EOF
# Auto-generated by run_test.sh

llm:
  base_url: "$SUET_LLM_URL"
  model: "$SUET_LLM_MODEL"
  api_key: "$SUET_LLM_API_KEY"

target:
  url: "$SUET_TARGET_URL"
  scan_paths:
    - "/"
    - "/login"
    - "/register"

source:
  root: "$SUET_SOURCE_ROOT"
  form_patterns:
    - "**/forms.py"
    - "**/schemas.py"
    - "**/models.py"
    - "**/validators.py"
    - "**/*_form.py"
    - "**/schema*.py"
  route_patterns:
    - "**/routes.py"
    - "**/api.py"
    - "**/endpoints.py"

logs:
  type: "$SUET_LOG_TYPE"
  docker_container: "$SUET_LOG_CONTAINER"
  error_patterns:
    - "ERROR"
    - "Exception"
    - "Traceback"
    - "500"
    - "Connection refused"

browser:
  headless: $SUET_HEADLESS
  timeout_ms: $SUET_TIMEOUT_MS
  viewport:
    width: 1280
    height: 720

pipeline:
  data_variations: $SUET_VARIATIONS
  max_pages: $SUET_MAX_PAGES
  artifacts_dir: "./artifacts"
EOF
ok "config.yaml written"

# ── Step 5: Manage OpenHands container (agent mode) ──────────
if [[ "$SUET_MODE" == "agent" && "$SUET_OPENHANDS_START" == "true" ]]; then
    info "Starting OpenHands Agent Server..."
    LLM_BASE_URL="$SUET_LLM_URL" \
    LLM_MODEL="$SUET_LLM_MODEL" \
    docker compose -f compose.yaml up -d 2>&1 | grep -v "WARN\|deprecated" || true

    info "Waiting for health check..."
    for i in $(seq 1 30); do
        if curl -sf "http://localhost:3005/health" >/dev/null 2>&1; then
            ok "OpenHands is healthy"
            break
        fi
        sleep 2
    done

    if ! curl -sf "http://localhost:3005/health" >/dev/null 2>&1; then
        warn "OpenHands health check timed out — proceeding anyway"
    fi
fi

# ── Step 6: Build CLI arguments ──────────────────────────────
CLI_ARGS=(
    run
    --target "$SUET_TARGET_URL"
    --source "$SUET_SOURCE_ROOT"
    --output "$SUET_OUTPUT_DIR"
    --llm-url "$SUET_LLM_URL"
    --llm-model "$SUET_LLM_MODEL"
    --variations "$SUET_VARIATIONS"
    --mode "$SUET_MODE"
    --agent-timeout "$SUET_OPENHANDS_TIMEOUT"
)

if [[ "$SUET_DRY_RUN" == "true" ]]; then
    CLI_ARGS+=(--dry-run)
fi

# ── Step 7: Run the pipeline ──────────────────────────────────
info ""
info "Running pipeline: ${CLI_ARGS[*]}"
echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"

if python -m src "${CLI_ARGS[@]}"; then
    ok ""
    ok "Pipeline complete."
    ok "Reports:"
    ok "  JSON: $SUET_OUTPUT_DIR/report/correlation_report.json"
    ok "  Markdown: $SUET_OUTPUT_DIR/report/summary.md"
    echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
else
    fail "Pipeline exited with error"
fi

# ── Step 8: Cleanup OpenHands (optional) ──────────────────────
if [[ "$SUET_MODE" == "agent" && "${SUET_OPENHANDS_STOP:-false}" == "true" ]]; then
    info "Stopping OpenHands container..."
    docker compose -f compose.yaml down
    ok "OpenHands stopped"
fi